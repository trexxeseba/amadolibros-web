export function imageContentHash(source) {
  return /\/([a-f0-9]{64})\.[a-z]+(?:[?#]|$)/i.exec(String(source || ''))?.[1]?.toLowerCase() || '';
}
export function isBookGalleryImage(source) {
  const path = String(source || '').split('?')[0];
  const sourceId = /(\d+-ML[A-Z]\d+_\d+)/.exec(path)?.[1];
  const verifiedLegacyRoute = /\/book-cover\/MLU640785075\/cover-[45]\.jpg$/.test(path) ||
    /\/book-cover\/MLU633445690\/cover-[567]\.jpg$/.test(path);
  return !NON_BOOK_IMAGE_HASHES.has(imageContentHash(source)) && !NON_BOOK_SOURCE_IDS.has(sourceId) && !verifiedLegacyRoute;
}
export function cleanBookGallery(sources = []) {
  const seen = new Set();
  return sources.filter(source => {
    if (!source || !isBookGalleryImage(source)) return false;
    const hash = imageContentHash(source);
    const identity = coverIdentity.get(hash) || hash || mlImageIdentity(source) || source;
    if (seen.has(identity)) return false;
    seen.add(identity);
    return true;
  });
}
